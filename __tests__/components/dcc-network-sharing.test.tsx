import { fireEvent, render, screen, waitFor, cleanup } from '@testing-library/react'
import { CollectiveNetworkArtwork } from '../../components/dcc/artwork/CollectiveNetworkArtwork'
import { CommunityAtlas } from '../../components/dcc/community/CommunityAtlas'
import { PILOT_PREVIEWS } from '../../lib/dcc/community/atlas'

jest.mock('next/dynamic', () => () => function Field() { return null })
const copy = jest.fn().mockResolvedValue(undefined)
beforeEach(() => {
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: copy } })
  Object.defineProperty(window, 'matchMedia', { configurable: true, value: () => ({ matches: false }) })
  HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', '') }
  global.fetch = jest.fn().mockResolvedValue({ ok: true, json: async () => ({ mode: 'preview', profiles: PILOT_PREVIEWS, intakeEnabled: false }) })
  copy.mockClear()
})
afterEach(cleanup)
it('copies the frozen edition, reloads it, and can return to the different living state', async () => {
  window.history.replaceState(null, '', '/network/artwork')
  const first = render(<CollectiveNetworkArtwork />)
  fireEvent.click(screen.getByRole('button', { name: 'need' }))
  fireEvent.click(screen.getByRole('button', { name: 'Freeze edition 001' }))
  fireEvent.click(screen.getByRole('button', { name: 'offer' }))
  fireEvent.click(screen.getByRole('button', { name: 'Edition' }))
  fireEvent.click(screen.getByRole('button', { name: 'Inspect BRIDGE' }))
  fireEvent.click(screen.getByRole('button', { name: 'Copy interactive study URL' }))
  await waitFor(() => expect(copy).toHaveBeenCalledTimes(1))
  const url = new URL(copy.mock.calls[0][0])
  expect(url.searchParams.get('fs')).toBe('need')
  expect(url.searchParams.get('s')).toBe('offer')
  expect(url.searchParams.get('view')).toBe('edition')
  first.unmount()
  window.history.replaceState(null, '', url.pathname + url.search)
  render(<CollectiveNetworkArtwork />)
  expect(screen.getByRole('button', { name: 'Edition' })).toHaveAttribute('aria-pressed', 'true')
  expect(screen.getByRole('button', { name: 'Download edition SVG' })).toBeEnabled()
  expect(screen.getByText('Facilitates exchanges')).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: 'Live' }))
  expect(screen.getByRole('button', { name: 'offer' })).toHaveAttribute('aria-pressed', 'true')
})
it('restores Atlas discovery and shares a Passport entry without its private form values', async () => {
  window.history.replaceState(null, '', '/network/community?interests=culture&q=Fabiola&profile=fabiola-larios&panel=passport')
  render(<CommunityAtlas />)
  expect(screen.getByRole('searchbox')).toHaveValue('Fabiola')
  await waitFor(() => expect(screen.getByRole('dialog')).toHaveAttribute('open'))
  fireEvent.change(screen.getByLabelText('Your display name'), { target: { value: 'Private guest' } })
  fireEvent.click(screen.getByRole('button', { name: 'Copy Passport preview link ↗' }))
  await waitFor(() => expect(copy).toHaveBeenCalledTimes(1))
  const url = new URL(copy.mock.calls[0][0])
  expect(url.searchParams.get('panel')).toBe('passport')
  expect(url.searchParams.get('q')).toBe('Fabiola')
  expect(url.searchParams.get('profile')).toBe('fabiola-larios')
  expect(url.toString()).not.toContain('Private')
  expect(global.fetch).toHaveBeenCalledTimes(1)
  expect((global.fetch as jest.Mock).mock.calls[0][0]).toBe('/api/marketing/community-atlas')
  fireEvent.click(screen.getByRole('button', { name: 'Close Passport preview' }))
  expect(new URLSearchParams(window.location.search).has('panel')).toBe(false)
  expect(screen.getByRole('heading', { name: 'Fabiola Larios' })).toBeVisible()
  fireEvent.change(screen.getByRole('searchbox'), { target: { value: 'no match' } })
  expect(screen.queryByRole('button', { name: 'Copy profile link ↗' })).not.toBeInTheDocument()
})
